from grid import Grid, check
from solve import run, Bad

S = []
def add(world, name, shape, end, pattern, scene, g, steps, tips, limit=0):
    bad = check(g); assert not bad, (name, bad)
    try: r = run(g, steps, end)
    except Bad as e: raise SystemExit(f'✗ {world}/{name}: {e}')
    S.append(dict(world=world, name=name, shape=shape, end=end, pattern=pattern, scene=scene,
                  art=g.art(), notes=g.notes, steps=r.log, moves=[list(m) for m in steps], tips=tips, size=(g.w, g.h), limit=limit))

def stairs_up(who, x0, y0, n, width=4):
    out = []
    for i in range(n):
        out.append(('jump', who, x0 + i*width, y0 - 1 - i))
        if i < n - 1: out.append(('walk', who, x0 + i*width + width - 1))
    return out

