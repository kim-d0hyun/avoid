from grid import Grid, check, FLOOR, stand
from solve import run, Bad

S = []   # dict 들

def add(world, name, scene, g, steps, tips):
    bad = check(g)
    assert not bad, (name, bad)
    try:
        r = run(g, steps)
    except Bad as e:
        raise SystemExit(f'✗ {world}/{name}: {e}')
    S.append(dict(world=world, name=name, scene=scene, art=g.art(), notes=g.notes,
                  steps=r.log, tips=tips))

