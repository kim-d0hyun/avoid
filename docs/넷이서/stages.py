from grid import Grid, check
from solve import run, Bad

S = []
def add(world, name, shape, end, pattern, scene, g, steps, tips):
    bad = check(g); assert not bad, (name, bad)
    try: r = run(g, steps, end)
    except Bad as e: raise SystemExit(f'✗ {world}/{name}: {e}')
    S.append(dict(world=world, name=name, shape=shape, end=end, pattern=pattern, scene=scene,
                  art=g.art(), notes=g.notes, steps=r.log, tips=tips, size=(g.w, g.h)))

def climb_stairs(who, x0, y0, steps, width=4):
    """계단 오르기 걸음. 한 단은 한 칸 위."""
    out = []; x, y = x0, y0
    for i in range(steps):
        x = x0 + i * width; y = y0 - 1 - i
        out.append(('jump', who, x, y))
        if i < steps - 1: out.append(('walk', who, x + width - 1))
    return out

